#!/usr/bin/env bash
set -euo pipefail

server_url="${SIM_DECK_SERVER_URL:-}"
output_dir="${SIM_DECK_OUTPUT_DIR:-/etc/sim-deck}"
image="${SIM_DECK_DEVICE_IMAGE:-}"
allow_insecure_http="${SIM_DECK_ALLOW_INSECURE_HTTP:-false}"
start=false
while [[ $# -gt 0 ]]; do
  case "$1" in
    --server-url) server_url="${2:?missing URL}"; shift 2 ;;
    --output-dir) output_dir="${2:?missing directory}"; shift 2 ;;
    --image) image="${2:?missing image}"; shift 2 ;;
    --start) start=true; shift ;;
    -h|--help)
      printf '%s\n' 'Usage: install-linux-device.sh --server-url https://server.example --image ghcr.io/orangeboychen/sim-deck-device:x.y.z [--output-dir DIR] [--start]'
      exit 0
      ;;
    *) printf 'Unknown argument: %s\n' "$1" >&2; exit 1 ;;
  esac
done
if [[ "$(uname -s)" != Linux || "$(id -u)" != 0 ]]; then
  printf '%s\n' "Run this installer as root on Linux." >&2
  exit 1
fi
for command in udevadm getent install docker; do
  command -v "$command" >/dev/null || { printf 'Missing required command: %s\n' "$command" >&2; exit 1; }
done
if [[ -z "$server_url" ]]; then
  printf '%s\n' "Set SIM_DECK_SERVER_URL or pass --server-url." >&2
  exit 1
fi
if [[ -z "$image" ]]; then
  printf '%s\n' "Set SIM_DECK_DEVICE_IMAGE or pass --image with an explicit published version tag." >&2
  exit 1
fi
case "$server_url" in https://*|http://*) ;; *) printf '%s\n' "Server URL must start with https:// or http://." >&2; exit 1 ;; esac
case "$allow_insecure_http" in
  true|false) ;;
  *) printf '%s\n' "SIM_DECK_ALLOW_INSECURE_HTTP must be true or false." >&2; exit 1 ;;
esac

property() {
  local key="$1" data="$2"
  printf '%s\n' "$data" | awk -F= -v key="$key" '$1 == key { print substr($0, length(key) + 2); exit }'
}
audio_node() {
  local kind="$1" serial="$2"
  case "$kind" in
    control) printf '%s' "${audio_control[$serial]:-}" ;;
    capture) printf '%s' "${audio_capture[$serial]:-}" ;;
    playback) printf '%s' "${audio_playback[$serial]:-}" ;;
  esac
}

declare -A at_node=() at_interface=() at_parent=() audio_control=() audio_capture=() audio_playback=()
for node in /dev/ttyUSB* /dev/ttyACM*; do
  [[ -e "$node" ]] || continue
  data="$(udevadm info --query=property --name="$node" 2>/dev/null || true)"
  [[ "$(property ID_VENDOR_ID "$data")" == 2c7c ]] || continue
  serial="$(property ID_SERIAL_SHORT "$data")"
  [[ -n "$serial" ]] || continue
  device_path="$(property ID_PATH "$data")"
  parent_path="${device_path%:*}"
  if [[ -n "${at_parent[$serial]:-}" && "${at_parent[$serial]}" != "$parent_path" ]]; then
    printf 'Duplicate USB serial %s belongs to multiple physical devices; refusing ambiguous mapping.\n' "$serial" >&2
    exit 1
  fi
  at_parent[$serial]="$parent_path"
  interface="$(property ID_USB_INTERFACE_NUM "$data")"
  if [[ -z "${at_node[$serial]:-}" || "$interface" == 02 ]]; then
    at_node[$serial]="$node"
    at_interface[$serial]="$interface"
  fi
done
for node in /dev/snd/controlC* /dev/snd/pcmC*D*c /dev/snd/pcmC*D*p; do
  [[ -e "$node" ]] || continue
  data="$(udevadm info --query=property --name="$node" 2>/dev/null || true)"
  [[ "$(property ID_VENDOR_ID "$data")" == 2c7c ]] || continue
  serial="$(property ID_SERIAL_SHORT "$data")"
  [[ -n "$serial" ]] || continue
  case "$node" in
    /dev/snd/controlC*) audio_control[$serial]="$node" ;;
    /dev/snd/pcm*C*D*c) audio_capture[$serial]="$node" ;;
    /dev/snd/pcm*C*D*p) audio_playback[$serial]="$node" ;;
  esac
done

serials=()
while IFS= read -r serial; do [[ -n "$serial" ]] && serials+=("$serial"); done < <(printf '%s\n' "${!at_node[@]}" | sort)
if [[ ${#serials[@]} -eq 0 ]]; then
  printf '%s\n' 'No Quectel modem with a stable USB serial identity was found.' >&2
  exit 1
fi
for serial in "${serials[@]}"; do
  missing_audio=()
  for kind in control capture playback; do
    [[ -n "$(audio_node "$kind" "$serial")" ]] || missing_audio+=("$kind")
  done
  if [[ ${#missing_audio[@]} -gt 0 ]]; then
    printf 'Modem %s does not expose all UAC nodes (missing: %s). Enable and verify UAC before installing.\n' "$serial" "${missing_audio[*]}" >&2
    exit 1
  fi
done
dialout_gid="$(getent group dialout | cut -d: -f3)"
audio_gid="$(getent group audio | cut -d: -f3)"
[[ -n "$dialout_gid" && -n "$audio_gid" ]] || { printf '%s\n' 'The dialout and audio groups must exist.' >&2; exit 1; }

rules_file=/etc/udev/rules.d/99-sim-deck.rules
compose_file="$output_dir/compose.yaml"
env_file="$output_dir/.env"
install -d -m 0750 "$output_dir" "$(dirname "$rules_file")"
if [[ -e "$rules_file" ]]; then cp -p "$rules_file" "$rules_file.bak.$(date +%s)"; fi
{
  printf '%s\n' '# Generated by install-linux-device.sh.'
  index=1
  for serial in "${serials[@]}"; do
    interface="${at_interface[$serial]}"
    if [[ -n "$interface" ]]; then
      printf 'SUBSYSTEM=="tty", ENV{ID_VENDOR_ID}=="2c7c", ENV{ID_SERIAL_SHORT}=="%s", ENV{ID_USB_INTERFACE_NUM}=="%s", SYMLINK+="sim-deck/modem-%s-at", GROUP="dialout", MODE="0660"\n' "$serial" "$interface" "$index"
    else
      printf 'SUBSYSTEM=="tty", ENV{ID_VENDOR_ID}=="2c7c", ENV{ID_SERIAL_SHORT}=="%s", SYMLINK+="sim-deck/modem-%s-at", GROUP="dialout", MODE="0660"\n' "$serial" "$index"
    fi
    for kind in control capture playback; do
      [[ -n "$(audio_node "$kind" "$serial")" ]] || continue
      case "$kind" in control) kernel='controlC*' ;; capture) kernel='pcmC*D*c' ;; playback) kernel='pcmC*D*p' ;; esac
      printf 'SUBSYSTEM=="sound", KERNEL=="%s", ATTRS{serial}=="%s", ATTRS{idVendor}=="2c7c", SYMLINK+="sim-deck/modem-%s-audio-%s", GROUP="audio", MODE="0660"\n' "$kernel" "$serial" "$index" "$kind"
    done
    index=$((index + 1))
  done
} > "$rules_file"
udevadm control --reload-rules
udevadm trigger --subsystem-match=tty --subsystem-match=sound

{
  printf '%s\n' 'x-device-defaults: &device-defaults'
  printf '  image: %s\n  restart: unless-stopped\n' "$image"
  printf '  group_add: [%s, %s]\n' "$dialout_gid" "$audio_gid"
  printf '%s\n' '  security_opt: [no-new-privileges:true]' '  cap_drop: [ALL]' '  read_only: true' '  tmpfs: [/tmp:rw,noexec,nosuid,size=16m]' '' 'services:'
  index=1
  for serial in "${serials[@]}"; do
    printf '  modem-%s:\n    <<: *device-defaults\n    hostname: sim-deck-modem-%s\n    environment:\n      SIM_DECK_SERVER_URL: ${SIM_DECK_SERVER_URL}\n      SIM_DECK_ALLOW_INSECURE_HTTP: ${SIM_DECK_ALLOW_INSECURE_HTTP:-false}\n      SIM_DECK_AT_DEVICE: /dev/sim-deck/at\n      SIM_DECK_AUDIO_MODE: alsa\n      SIM_DECK_STATE_DIRECTORY: /var/lib/sim-deck\n    devices:\n      - /dev/sim-deck/modem-%s-at:/dev/sim-deck/at\n' "$index" "$index" "$index"
    for kind in control capture playback; do
      [[ -n "$(audio_node "$kind" "$serial")" ]] || continue
      case "$kind" in
        control) target=/dev/snd/controlC0 ;;
        capture) target=/dev/snd/pcmC0D0c ;;
        playback) target=/dev/snd/pcmC0D0p ;;
      esac
      printf '      - /dev/sim-deck/modem-%s-audio-%s:%s\n' "$index" "$kind" "$target"
    done
    printf '    volumes:\n      - modem-%s-state:/var/lib/sim-deck\n    ports:\n      - 127.0.0.1:%s:8080\n\n' "$index" "$((18080 + index))"
    index=$((index + 1))
  done
  printf '%s\n' 'volumes:'
  for index in $(seq 1 "${#serials[@]}"); do printf '  modem-%s-state:\n' "$index"; done
} > "$compose_file"
printf 'SIM_DECK_SERVER_URL=%s\n' "$server_url" > "$env_file"
printf 'SIM_DECK_ALLOW_INSECURE_HTTP=%s\n' "$allow_insecure_http" >> "$env_file"
chmod 0640 "$env_file" "$compose_file"

printf 'Discovered %s modem(s).\nGenerated %s and %s.\n' "${#serials[@]}" "$rules_file" "$compose_file"
printf 'Start with: docker compose --env-file %s -f %s up -d\n' "$env_file" "$compose_file"
if [[ "$start" == true ]]; then docker compose --env-file "$env_file" -f "$compose_file" up -d; fi
